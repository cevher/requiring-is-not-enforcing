def fmt(v, d=4):
    if pd.isna(v):
        return "—"
    if isinstance(v, float):
        return f"{v:.{d}f}".rstrip("0").rstrip(".") if d > 2 else f"{v:.{d}f}"
    return str(v)


def md_table(df, cols, headers, digits=None):
    digits = digits or {}
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for _, r in df.iterrows():
        cells = [fmt(r[c], digits.get(c, 4)) if c in r else "—" for c in cols]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


