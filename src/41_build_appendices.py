"""
41_build_appendices.py

Generates Appendices A-C of the manuscript from the project data, so that the
firm list, the fold composition and the sensitivity table are never retyped.

  Appendix A  equity universe (63 firms, 11 GICS sectors)
  Appendix B  temporal validation folds: what the per-fold protocol discarded
              and what the pooled protocol evaluates
  Appendix C  sensitivity of the reliability layer's design constants

Output: Appendices_v8.md, written next to the manuscript.
"""

import pandas as pd

from config import PROJECT_ROOT, LABEL_DIR, REPORT_DIR

OUT = PROJECT_ROOT.parent / "Appendices_v8.md"
P = []


def table(df, headers=None):
    headers = headers or list(df.columns)
    lines = ["| " + " | ".join(str(h) for h in headers) + " |",
             "|" + "|".join(["---"] * len(headers)) + "|"]
    # itertuples, not iterrows: iterrows upcasts a mixed int/float row to a single
    # dtype and would print integer counts as 2011.0 / 12.0.
    for r in df.itertuples(index=False, name=None):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |")
    return "\n".join(lines)


# ------------------------------------------------------------------ Appendix A
u = pd.read_csv(PROJECT_ROOT / "data_raw" / "metadata" / "universe.csv")
u = u.sort_values(["sector", "ticker"]).reset_index(drop=True)

P.append("# Appendices\n")
P.append("Generated by `src/41_build_appendices.py`.\n")
P.append("\n## Appendix A. Equity universe\n")
P.append(f"The universe contains {len(u)} firms across {u['sector'].nunique()} GICS sectors, "
         "listed here in full so that the sample is reproducible from public sources. "
         "Sector membership is used only to aggregate firm-level network metrics into "
         "sector-level relational evidence; it plays no role in the risk-scoring layer.\n")

counts = (u.groupby("sector").size().sort_values(ascending=False)
            .rename("Firms").reset_index().rename(columns={"sector": "Sector"}))
P.append("\n**Table A.1** Sector composition\n")
P.append(table(counts))

P.append("\n\n**Table A.2** Full ticker list\n")
listing = u.rename(columns={"ticker": "Ticker", "company_name": "Company", "sector": "Sector"})
P.append(table(listing[["Ticker", "Company", "Sector"]]))

# ------------------------------------------------------------------ Appendix B
folds = pd.read_csv(REPORT_DIR / "expanding_window_fold_summary.csv")
main = folds[folds["target"] == "next_20d_external_stress"].copy()

P.append("\n\n## Appendix B. Temporal validation folds\n")
P.append(
    "Models are trained on an expanding window and evaluated one test year at a "
    "time from 2011 onwards, with the most recent 24 months of each training "
    "period reserved for probability calibration.\n\n"
    "Table B.1 reports the composition of every fold, including the three that the "
    "per-fold protocol discarded. A fold was skipped when the target took a single "
    "value inside the test year: 2013 and 2017 because no stress window occurred, "
    "and 2020 because every month of the year was a stress month. Discarding 2020 "
    "removes the most informative episode in the evaluation window from a "
    "systemic-risk evaluation, and discarding the two quiet years removes the "
    "opposite tail. The revised protocol therefore pools out-of-sample predictions "
    "across all test years and computes each metric once on the pooled set, so a "
    "year with no within-year label variation still contributes its observations.\n")

main = main.rename(columns={
    "test_year": "Test year", "status": "Status", "n_train": "Train n",
    "n_calibration": "Calibration n", "n_test": "Test n",
    "train_positive_share": "Train pos. share", "test_positive_share": "Test pos. share"})
for c in ["Train pos. share", "Test pos. share"]:
    main[c] = main[c].astype(float).round(3)
main["Status"] = main["Status"].replace({
    "used": "used", "skipped_class_imbalance": "discarded (single-valued target)"})

P.append("\n**Table B.1** Fold composition for the primary target\n")
P.append(table(main[["Test year", "Status", "Train n", "Calibration n", "Test n",
                     "Train pos. share", "Test pos. share"]]))

used = int((main["Status"] == "used").sum())
disc = int(len(main) - used)
P.append(f"\nThe per-fold protocol used {used} of {len(main)} folds, giving "
         f"{used * 12} evaluated records; {disc} folds were discarded. "
         "The pooled protocol evaluates 179 records over the same period.\n")

snap = pd.read_csv(LABEL_DIR / "label_variants_snapshots.csv", parse_dates=["date"])
snap["Year"] = snap["date"].dt.year
comp = (snap[snap["Year"] >= 2011]
        .groupby("Year")
        .agg(Snapshots=("date", "size"),
             **{"L1 positive share": ("next20_L1_leakfree", "mean"),
                "L4 positive share": ("next20_L4_fwd_realized_vol", "mean")})
        .round(3).reset_index())
comp["Year"] = comp["Year"].astype(int)
comp["Snapshots"] = comp["Snapshots"].astype(int)
P.append("\n**Table B.2** Pooled evaluation window: snapshots and positive share per year\n")
P.append(table(comp))

# ------------------------------------------------------------------ Appendix C
sens = pd.read_csv(REPORT_DIR / "reliability_sensitivity.csv")

P.append("\n\n## Appendix C. Sensitivity of the reliability layer\n")
P.append(
    "The reliability layer is a rule set whose six cut-offs are design parameters "
    "rather than estimates. Each is perturbed one at a time while the others are "
    "held at their operating values, and the effect is measured on all 144 decision "
    "records. Agreement columns report the share of records whose abstention flag "
    "or confidence class is unchanged relative to the operating configuration; the "
    "last column reports how many of the ten snapshots used in the generation "
    "experiment change either flag.\n\n"
    "The re-implementation used here reproduces the stored decision layer exactly "
    "(confidence and abstention agreement 1.000 at the operating values), so the "
    "table is comparable to the published records.\n")

sens_disp = sens.copy()
sens_disp["parameter"] = sens_disp["parameter"].replace({
    "conf_high": "High-confidence margin", "conf_med": "Medium-confidence margin",
    "gap": "Disagreement score gap", "err_cut": "Bin error-rate cut-off",
    "brier_cut": "Bin Brier cut-off", "abstain_band": "Abstention half-width",
    "min_bin_n": "Minimum bin history"})
sens_disp["value"] = sens_disp.apply(
    lambda r: f"**{r['value']:g}**" if r["is_baseline"] else f"{r['value']:g}", axis=1)
sens_disp = sens_disp.rename(columns={
    "parameter": "Parameter", "value": "Value", "abstention_rate": "Abstention rate",
    "disagreement_rate": "Disagreement rate", "conf_low": "Low", "conf_medium": "Medium",
    "conf_high": "High", "abstention_agreement_with_base": "Abstention agree.",
    "confidence_agreement_with_base": "Confidence agree.",
    "llm_sample_flags_changed": "Sample flags changed"})

P.append("\n**Table C.1** One-at-a-time sensitivity of the reliability layer "
         "(operating values in bold)\n")
P.append(table(sens_disp[["Parameter", "Value", "Abstention rate", "Disagreement rate",
                          "Low", "Medium", "High", "Abstention agree.",
                          "Confidence agree.", "Sample flags changed"]]))

p = sens[~sens["is_baseline"]]
base_abst = float(sens.loc[sens["is_baseline"] & (sens["parameter"] == "conf_high"),
                           "abstention_rate"].iloc[0])
P.append(
    f"\nAcross all perturbations the abstention rate stays within "
    f"{p['abstention_rate'].min():.3f}-{p['abstention_rate'].max():.3f} "
    f"(operating value {base_abst:.3f}); abstention flags agree with the operating "
    f"configuration on at least {p['abstention_agreement_with_base'].min()*100:.1f}% of records "
    f"and confidence classes on at least {p['confidence_agreement_with_base'].min()*100:.1f}%. "
    f"At most {int(p['llm_sample_flags_changed'].max())} of the ten generation snapshots change "
    "either flag under any single perturbation. The layer is therefore stable in the "
    "quantities that reach the language model.\n\n"
    "Two qualifications. First, the confidence margin and the minimum bin history are the "
    "parameters that matter: a 0.05 change in the high-confidence margin, or raising the "
    "minimum bin history from 10 to 20 prior observations, reclassifies roughly one record "
    "in seven between confidence levels, although it moves almost no abstention decisions. "
    "Second, the minimum bin history is perturbed upward only. Lowering it would require "
    "bin accuracy and Brier statistics that were never stored for bins below the operating "
    "threshold, and the probability-bin width of 0.2 is likewise fixed by the stored "
    "records. Both would require re-running the reliability estimation.\n")

OUT.write_text("\n".join(P), encoding="utf-8")
print(f"Wrote {OUT}")
